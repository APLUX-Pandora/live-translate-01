class Handler(BaseHTTPRequestHandler):
    def setup(self):
        super().setup()
        self.connection.settimeout(3)

    def log_message(self, fmt, *args):
        pass

    def _json(self, obj, code=200):
        b = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(b)))
        self.end_headers()
        self.wfile.write(b)

    def _body(self):
        n = int(self.headers.get("Content-Length") or 0)
        return json.loads(self.rfile.read(n) or b"{}")

    def do_GET(self):
        p = self.path.split("?")[0]
        if p in ("/", "/index.html"):
            return self._file(f"{STATIC}/index.html", "text/html; charset=utf-8")
        if p in ("/pandora-mark.svg", "/favicon.ico"):
            return self._file(f"{STATIC}/pandora-mark.svg", "image/svg+xml")
        if p == "/logo.png":
            return self._file(f"{STATIC}/logo.png", "image/png")
        if p == "/pcm-worklet.js":
            return self._file(f"{STATIC}/pcm-worklet.js", "text/javascript; charset=utf-8")
        if p in ("/translation.js", "/transport.js"):
            return self._file(f"{STATIC}{p}", "text/javascript; charset=utf-8")
        if p == "/api/videos":
            return self._json({"videos": S.videos(), **S.info()})
        if p == "/api/events":
            return self._events()
        if p.startswith("/media/"):
            f = media_path(urllib.parse.unquote(p[len("/media/"):]))
            media = S.media_details(f) if f else None
            if media:
                return self._file(f, media.content_type)
        self.send_error(404)

    def do_PUT(self):
        p, q = self.path.split("?")[0], urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
        if p == "/api/upload":
            n = int(self.headers.get("Content-Length") or 0)
            if n <= 0:
                return self._json({"error": "empty upload"}, 400)
            res, err = S.upload(q.get("name", ["video.mp4"])[0], self.rfile, n, q.get("lang", ["zh"])[0])
            return self._json(res if err is None else {"error": err}, 200 if err is None else 400)
        self.send_error(404)

    def do_POST(self):
        if S.stopping.is_set():
            return self._json({'error': 'Service is stopping'}, 503)
        p = self.path.split("?")[0]
        if p == "/api/audio":                           # raw PCM16 body, ?sid=<run>
            q = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
            try:
                n = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                return self._json({"error": "Invalid audio length"}, 400)
            if not 0 < n <= MAX_AUDIO_CHUNK:
                return self._json({"error": "Invalid PCM16 chunk length"}, 400)
            timeout = self.connection.gettimeout()
            try:
                self.connection.settimeout(10)
                data = self.rfile.read(n)
            except TimeoutError:
                return self._json({"error": "Audio upload timed out before acceptance"}, 408)
            finally:
                self.connection.settimeout(timeout)
            if len(data) != n:
                return self._json({"error": "Incomplete audio body; retry this chunk"}, 400)
            try:
                sid = int(q.get("sid", ["-1"])[0])
            except ValueError:
                sid = -1
            if data and len(data) % 2 == 0:
                try:
                    sequence = int(q["seq"][0]) if "seq" in q else None
                except ValueError:
                    sequence = None
                result, error = S.push_audio(sid, data, sequence)
                return self._json(result if error is None else {"error": error}, 200 if error is None else 429 if error == AUDIO_BUSY else 409)
            return self._json({"error": "Expected nonempty PCM16 audio"}, 400)
        b = self._body()
        if p == "/api/start":
            sid, err = S.start(b.get("video", ""), b.get("offset_s", 0.0), b.get("jump", False), b.get("target"), b.get("translation_enabled"), b.get("audio_sequence", False))
            return self._json({"sid": sid} if err is None else {"error": err, "reload_required": S.needs_reload()}, 200 if err is None else 409)
        if p == "/api/end":
            error = S.end(b.get("sid"), b.get("next_seq"))
            return self._json({} if error is None else {"error": error}, 200 if error is None else 409)
        if p == "/api/stop":
            S.stop()
            return self._json({})
        if p == "/api/reload":
            error = S.configure(S.clock, S.lang, force=True)
            return self._json({} if error is None else {"error": error}, 200 if error is None else 409)
        if p == "/api/config":
            err = S.configure(str(b.get("clock_ms")), str(b.get("lang")))
            return self._json({} if err is None else {"error": err}, 200 if err is None else 409)
        if p == "/api/translation-enabled":
            error = S.set_translation_enabled(b.get("enabled"))
            return self._json({"error": error} if error else {"enabled": S.translations.enabled, "epoch": S.translations.epoch, "active": S.translations.worker_active}, 409 if error else 200)
        if p == "/api/translation-target":
            error = S.set_target(b.get("target"))
            return self._json({"error": error} if error else {}, 409 if error else 200)
        if p == "/api/video-language":
            error = S.set_video_language(b.get("video", ""), b.get("lang"))
            return self._json({"error": error} if error else {}, 409 if error else 200)
        if p == "/api/cancel":
            error = S.cancel(b.get("sid"))
            return self._json({"error": error} if error else {}, 409 if error else 200)
        if p == "/api/delete":
            err = S.delete(b.get("video", ""))
            return self._json({} if err is None else {"error": err}, 200 if err is None else 400)
        self.send_error(404)

    def _events(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        q = queue.Queue(maxsize=256)
        S.subs.append(q)
        try:
            self.wfile.write(f"data: {json.dumps(S.info())}\n\n".encode())
            self.wfile.write(f"data: {json.dumps(S.snapshot(), ensure_ascii=False)}\n\n".encode())
            if S.state == "reload":
                self.wfile.write(f"data: {json.dumps({'type': 'loading', 'on': True})}\n\n".encode())
            if S.sys_hist:
                h = {"type": "sys_hist", "dram_total_mb": S.dram_total, "pts": list(S.sys_hist)}
                self.wfile.write(f"data: {json.dumps(h)}\n\n".encode())
            self.wfile.flush()
            while not S.stopping.is_set() and q in S.subs:
                try:
                    ev = q.get(timeout=.5)
                    self.wfile.write(f"data: {json.dumps(ev, ensure_ascii=False)}\n\n".encode())
                except queue.Empty:
                    self.wfile.write(b": keepalive\n\n")
                self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError, TimeoutError, OSError):
            pass
        finally:
            try:
                S.subs.remove(q)
            except ValueError:
                pass

    def _file(self, path, ctype):
        size = os.path.getsize(path)
        ranges = self.headers.get_all("Range", [])
        start, end = 0, size - 1
        if ranges:
            match = re.fullmatch(r"bytes=([0-9]*)-([0-9]*)", ranges[0].strip(),
                                 flags=re.IGNORECASE) if len(ranges) == 1 else None
            if match and any(match.groups()):
                a, b = match.groups()

                def bounded_number(value):
                    digits = value.lstrip("0")
                    return min(size, int(digits or "0")) if len(digits) <= len(str(size)) else size

                if a:
                    start = bounded_number(a)
                    end = min(end, bounded_number(b)) if b else end
                else:
                    start = size - bounded_number(b)
            else:
                start = size
            if start > end:
                self.send_response(416)
                self.send_header("Content-Range", f"bytes */{size}")
                self.send_header("Accept-Ranges", "bytes")
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            self.send_response(206)
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        else:
            self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(end - start + 1))
        self.end_headers()
        try:
            with open(path, "rb") as f:
                f.seek(start)
                left = end - start + 1
                while left > 0:
                    chunk = f.read(min(1 << 16, left))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    left -= len(chunk)
        except (BrokenPipeError, ConnectionResetError):
            pass


def main():
    global S, MODELS, TRANSLATION_MODELS
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8766)
    ap.add_argument("--models", type=Path, default=Path(ROOT)/"models"/"asr")
    ap.add_argument("--translation-models", type=Path, default=Path(ROOT)/"models"/"translation")
    ap.add_argument("--media-dir", type=Path, help="Existing independent media directory")
    a = ap.parse_args()
    MODELS, TRANSLATION_MODELS = a.models, a.translation_models
    global MEDIA, UPLOADS
    if a.media_dir:
        MEDIA = str(Path(a.media_dir).resolve(strict=True))
        UPLOADS = str(Path(MEDIA)/'uploads')
        Path(UPLOADS).mkdir(parents=True, exist_ok=True)
    signals = (signal.SIGTERM, signal.SIGINT)
    done = threading.Event()
    control_fd = int(os.environ["LIVE_TRANSLATE_STOP_FD"]) if "LIVE_TRANSLATE_STOP_FD" in os.environ else None
    old_handlers = {s: signal.signal(s, lambda *_: STOP.set()) for s in signals}

    def receive():
        while not done.is_set():
            readable, _, _ = select.select([control_fd], [], [], .2)
            if readable and os.read(control_fd, 1) in (b"S", b""):
                STOP.set()
                return

    receiver = None
    if control_fd is not None:
        receiver = threading.Thread(target=receive)
        receiver.start()
    srv = None
    try:
        S = Session()
        if STOP.is_set():
            return
        srv = ThreadingHTTPServer(("0.0.0.0", a.port), Handler)
        srv.daemon_threads = False
        srv.timeout = .2
        print(f"[demo] engine ready in {S.init_s:.1f}s, {S.clock} ms clock, lang {S.lang}; http://0.0.0.0:{a.port}/", flush=True)
        while not STOP.is_set():
            srv.handle_request()
    except InterruptedError:
        if not STOP.is_set():
            raise
    finally:
        try:
            if S is not None:
                S.stopping.set()
            if srv is not None:
                srv.server_close()
            if S is not None:
                S.close()
        finally:
            done.set()
            if receiver is not None:
                receiver.join()
                os.close(control_fd)
            for s, handler in old_handlers.items():
                signal.signal(s, handler)


if __name__ == "__main__":
    main()
