def media_path(vid):
    """Resolve a media file by its relative path within the media directory."""
    p = os.path.normpath(os.path.join(MEDIA, vid))      # lexical check (media files may be symlinks, e.g. a dev checkout)
    return p if p.startswith(os.path.normpath(MEDIA) + os.sep) and os.path.isfile(p) else None


def meta_of(path):
    # The suffix cannot be generated by either legacy JSON naming scheme.
    return path + ".meta"


def videos_with_stem(stem):
    directory, name = os.path.split(stem)
    with os.scandir(directory or ".") as entries:
        for entry in entries:
            base, ext = os.path.splitext(entry.name)
            if base == name and ext.lower() in MEDIA_TYPES and entry.is_file():
                yield entry.path


def owns_full_name_json(path):
    if Path(path).suffix.lower() not in MEDIA_TYPES or not os.path.isfile(path + ".json") or not os.path.isfile(path):
        return False
    # If a longer video needs this JSON as its stem sidecar, keep legacy
    # ownership. A full-name layout gives every longer video its own JSON.
    return all(owns_full_name_json(video) for video in videos_with_stem(path))


def video_sidecars(path, *, deleting=False):
    yield meta_of(path)
    if owns_full_name_json(path):
        yield path + ".json"
    stem = os.path.splitext(path)[0]
    legacy = stem + ".json"
    if os.path.isfile(legacy) and not owns_full_name_json(stem):
        if not deleting or all(video == path for video in videos_with_stem(stem)):
            yield legacy


def video_metadata(path):
    for sidecar in video_sidecars(path):
        try:
            metadata = json.loads(Path(sidecar).read_text())
        except FileNotFoundError:
            continue
        except (OSError, ValueError):
            break
        return metadata if isinstance(metadata, dict) else {}
    return {}


def video_lang(path):
    lang = video_metadata(path).get("lang", "zh")
    return lang if lang in LANGS else "zh"


class MediaInfo(NamedTuple):
    kind: str
    duration_s: float | None
    content_type: str
    audio_index: int


def probe_media(path, ext):
    demuxer, video_type, audio_type = MEDIA_TYPES[ext]
    result = subprocess.run(
        ["ffprobe", "-v", "error", "-protocol_whitelist", "file", "-f", demuxer,
         "-show_entries", "format=duration:stream=index,codec_type,codec_name:stream_disposition",
         "-of", "json", path],
        check=True, capture_output=True, text=True, timeout=30,
    )
    probe = json.loads(result.stdout)
    streams = probe.get("streams", [])
    audio = [stream for stream in streams if stream.get("codec_type") == "audio"]
    if not audio:
        return None
    track = next((stream for stream in audio if stream["disposition"]["default"]), audio[0])
    has_picture = any(stream.get("codec_type") == "video" and not stream["disposition"]["attached_pic"]
                      for stream in streams)
    if (has_picture and video_type is None) or (ext == ".m4a" and track.get("codec_name") != "aac"):
        return None
    try:
        duration = round(float(probe["format"]["duration"]), 1)
    except (KeyError, ValueError):
        duration = None
    return MediaInfo("video" if has_picture else "audio", duration,
                     video_type if has_picture else audio_type, track["index"])


def can_decode_audio(path, ext, index):
    try:
        decoded = subprocess.run(
            ["ffmpeg", "-nostdin", "-v", "error", "-xerror", "-protocol_whitelist", "file",
             "-f", MEDIA_TYPES[ext][0], "-i", path, "-map", f"0:{index}",
             "-frames:a", "1", "-f", "s16le", "pipe:1"],
            check=True, capture_output=True, timeout=30,
        )
        return bool(decoded.stdout)
    except (OSError, subprocess.SubprocessError):
        return False


class Session:
    def __init__(self):
        self.lock = threading.Lock()
        self.subs = []
        self.stopping = threading.Event()
        self.asr = self.translations = None
        self.worker_thread = self.sysmon_thread = None
        self._closed = False
        self.reload_required = False
        self.model_error = None
        self.audio_next_seq = 0
        self.last_audio_digest = None
        self.sequenced_audio = False
        self.audio = collections.deque()
        self.buffered_audio = 0
        self.ended = False
        self.sid, self.state, self.video = 0, "idle", None
        self.lang, self.clock = "en", "160"
        self.target = target_for(self.lang)
        self.offset_s, self.jump = 0.0, False
        self.transcript = ""
        self.text_revision = 0
        self.init_s = 0.0
        self.media_info = {}
        self.sys_hist = collections.deque(maxlen=240)
        self.dram_total = 0
        try:
            self.load_workers()
            self.worker_thread = threading.Thread(target=self.worker)
            self.worker_thread.start()
            self.sysmon_thread = threading.Thread(target=self.sysmon)
            self.sysmon_thread.start()
        except BaseException:
            self.close()
            raise

    def load_workers(self):
        started = time.monotonic()
        self.asr = ASRWorker(str(MODELS), STOP)
        self.translations = TranslationService(TRANSLATION_MODELS, self.broadcast, stop_event=STOP, replay_limit=None)
        self.init_s = time.monotonic() - started

    def close_workers(self, *, allow_failed_worker=False):
        try:
            if self.translations is not None:
                self.translations.close(allow_failed_worker=allow_failed_worker)
        finally:
            if self.asr is not None:
                self.asr.close(allow_failed_worker=allow_failed_worker)

    # ------------------------------------------------------------ events
    def broadcast(self, ev):
        for q in list(self.subs):
            try:
                q.put_nowait(ev)
            except queue.Full:
                # A slow SSE reader reconnects to the bounded replay snapshot.
                try:
                    self.subs.remove(q)
                except ValueError:
                    pass

    def info(self):
        translation = self.translations
        return {"type": "info", "sid": self.sid, "state": self.state, "video": self.video,
                    "audio_next_seq": self.audio_next_seq, "reload_required": self.needs_reload(),
                    "model_error": self.model_error, "lang": self.lang, "clocks": [self.clock],
                    "clock_ms": int(self.clock), "init_s": round(self.init_s, 1),
                    "translation_target": self.target, "translation_enabled": translation.enabled,
                    "translation_epoch": translation.epoch, "translation_active": translation.worker_active,
                    "languages": LANGUAGES, "source_languages": list(SOURCE_LANGUAGES)}

    def media_details(self, path):
        ext = Path(path).suffix.lower()
        if ext not in MEDIA_TYPES:
            return None
        try:
            st = os.stat(path)
        except OSError:
            return None
        identity = (st.st_ino, st.st_size, st.st_mtime_ns)
        cached = self.media_info.get(path)
        if cached is not None and cached[0] == identity:
            return cached[1]
        try:
            media = probe_media(path, ext)
        except (OSError, ValueError, subprocess.SubprocessError):
            # A failed probe does not establish that the file is unsupported.
            return None
        self.media_info[path] = identity, media
        return media

    def videos(self):
        out = []
        for d, builtin in ((MEDIA, True), (UPLOADS, False)):
            if not os.path.isdir(d):
                continue
            for entry in sorted(Path(d).iterdir()):
                if not entry.is_file():
                    continue
                p = str(entry)
                media = self.media_details(p)
                if media:
                    default = builtin and entry.name == DEFAULT_VIDEO
                    name = "Beyond the README" if default else entry.name
                    out.append({"id": os.path.relpath(p, MEDIA), "name": name,
                                "builtin": builtin, "default": default, "duration_s": media.duration_s,
                                "lang": video_lang(p), "kind": media.kind})
        return out

    def sysmon(self):
        """Board DRAM every 0.5 s: system used = MemTotal - MemAvailable."""
        while not self.stopping.is_set():
            m = {}
            for line in Path("/proc/meminfo").read_text().splitlines():
                k, v = line.split(":", 1)
                m[k] = int(v.split()[0]) // 1024
            ev = {"type": "sys", "t": round(time.time(), 2), "dram_total_mb": m["MemTotal"],
                  "dram_used_mb": m["MemTotal"] - m["MemAvailable"]}
            self.dram_total = m["MemTotal"]
            self.sys_hist.append([ev["t"], ev["dram_used_mb"]])
            self.broadcast(ev)
            self.stopping.wait(0.5)

    # ------------------------------------------------------------ control (HTTP threads)
    def start(self, vid, offset_s=0.0, jump=False, target=None, translation_enabled=None, sequenced=False):
        """New run of `vid` from offset_s (a fresh engine session at that point of the video). jump = the page moved the
        playhead during a run (source and translation start a new shared session)."""
        p = media_path(vid)
        if p is None or self.media_details(p) is None:
            return None, "Unknown media file"
        if translation_enabled is not None and not isinstance(translation_enabled, bool):
            return None, "Translation enabled must be a boolean"
        try:
            offset = max(0.0, float(offset_s))
        except (ValueError, TypeError, OverflowError):
            return None, "Invalid playback position"
        with self.lock:
            if self.state == "reload":
                return None, "Engine is loading"
            if self.needs_reload():
                return None, "Model requires reload before starting a new recording"
            language = video_lang(p)
            if language != self.lang:
                return None, f"This file is {language}, the selected language is {self.lang}"
            try:
                selected = target_for(self.lang, target if target is not None else self.target)
                self.translations.begin(self.sid + 1, self.lang, selected, enabled=translation_enabled)
            except (TypeError, ValueError, RuntimeError) as error:
                return None, str(error)
            self.sid += 1
            self.target = selected
            self.video, self.offset_s, self.jump = vid, offset, bool(jump)
            self.ended = False
            self.sequenced_audio = bool(sequenced)
            self.audio_next_seq = 0
            self.last_audio_digest = None
            self.audio.clear()
            self.buffered_audio = 0
            self.transcript, self.text_revision = "", 0
            self.state = "reset"
            return self.sid, None

    def needs_reload(self):
        return self.reload_required or (self.translations is not None and
                                        self.translations.reload_required.is_set())

    def push_audio(self, sid, pcm16, sequence=None):
        """Acknowledge ordered audio once, even if the previous HTTP response was lost."""
        if not pcm16 or len(pcm16) % 2 or len(pcm16) > MAX_AUDIO_CHUNK:
            return None, "Expected nonempty PCM16 audio"
        digest = hashlib.sha256(pcm16).hexdigest()
        with self.lock:
            if sid != self.sid:
                return None, "Recording has changed; this audio was not accepted"
            if self.needs_reload():
                return None, "Model requires reload; the recording is incomplete"
            if self.sequenced_audio:
                if type(sequence) is not int or sequence < 0:
                    return None, "An audio sequence number is required"
                if sequence == self.audio_next_seq-1 and digest == self.last_audio_digest:
                    return {"next_seq": self.audio_next_seq, "duplicate": True}, None
                if sequence != self.audio_next_seq:
                    return None, "Audio sequence gap or conflicting retry"
            if self.state not in ("reset", "running") or self.ended:
                return None, "Recording no longer accepts audio"
            if self.buffered_audio + len(pcm16) > MAX_BUFFERED_AUDIO:
                return None, AUDIO_BUSY
            self.audio.append((sid, pcm16))
            self.buffered_audio += len(pcm16)
            if self.sequenced_audio:
                self.audio_next_seq += 1
                self.last_audio_digest = digest
            return {"next_seq": self.audio_next_seq}, None

    def end(self, sid, next_sequence=None):
        """Only finish a sequenced recording after every captured chunk is acknowledged."""
        with self.lock:
            if sid != self.sid:
                return "Recording has changed"
            if self.needs_reload():
                return "Model requires reload; the recording is incomplete"
            if self.state == "cancelled":
                return "Recording was cancelled"
            if self.sequenced_audio and (type(next_sequence) is not int or next_sequence != self.audio_next_seq):
                return "Audio is not fully acknowledged; retry the pending upload"
            self.ended = True
        return None

    def stop(self):
        with self.lock:
            if self.state == "reload":
                return
            # Finish accepted audio and translate its last phrase before stopping.
            if self.state in ("reset", "running"):
                self.ended = True
                return
        self.broadcast({"type": "state", "state": "idle"})

    def cancel(self, sid):
        with self.lock:
            if sid != self.sid or self.state == "reload":
                return "Recording has changed"
            self.translations.cancel()
            self.audio.clear()
            self.buffered_audio = 0
            self.ended = True
            self.state = "cancelled"
            self.broadcast({"type": "state", "sid": sid, "state": "cancelled"})

    def snapshot(self):
        with self.lock:
            result = self.translations.snapshot()
            result.update(sid=self.sid, paragraphs=[self.source_row()] if self.text_revision else [],
                          state=self.state)
            return result

    def source_row(self):
        return {"id": 1, "text": self.transcript, "start_s": self.offset_s, "revision": self.text_revision}

    def set_translation_enabled(self, enabled):
        with self.lock:
            try:
                self.translations.set_enabled(enabled)
            except (TypeError, ValueError, RuntimeError) as error:
                return str(error)
        return None

    def set_target(self, target):
        try:
            target = target_for(self.lang, target)
        except ValueError as error:
            return str(error)
        with self.lock:
            if self.state in ("running", "reset", "reload") or self.translations.snapshot()["pending"]:
                return "Stop and wait for translation to finish before changing languages"
            if self.target == target:
                return None
            self.target = target
            self.sid += 1
            self.state = "idle"
            self.transcript, self.text_revision = "", 0
            self.translations.begin(self.sid, self.lang, target)
        self.broadcast(self.info())
        return None

    def set_video_language(self, video, language):
        with self.lock:
            path = media_path(video)
            if path is None or Path(path).suffix.lower() not in MEDIA_TYPES or language not in SOURCE_LANGUAGES:
                return "Unknown media file or unsupported source language"
            if self.state in ("running", "reset", "reload") or self.translations.snapshot()["pending"]:
                return "Stop and wait for translation to finish before changing languages"
            metadata = video_metadata(path)
            metadata["lang"] = language
            temp = meta_of(path)+".tmp"
            with open(temp, "w") as f:
                json.dump(metadata, f)
            os.replace(temp, meta_of(path))
        return None

    def configure(self, clock, lang, force=False):
        if clock not in CLOCKS or lang not in LANGS:
            return "Invalid audio clock or language"
        with self.lock:
            if self.state == "reload":
                return "Engine is loading"
            if not self.needs_reload() and (self.state in ("running", "reset") or self.translations.snapshot()["pending"]):
                return "Stop and wait for translation to finish before changing languages"
            if not force and not self.needs_reload():
                if self.lang != lang:
                    self.lang = lang
                    self.target = target_for(lang)
                    self.sid += 1
                    self.transcript, self.text_revision = "", 0
                    self.translations.begin(self.sid, lang, self.target)
                return None
            self.translations.cancel()
            self.state = "reload"
            self.lang = lang
            if self.target == lang:
                self.target = target_for(lang)
            self.broadcast({"type": "loading", "on": True, "clock_ms": clock, "lang": lang})
        return None

    def upload(self, name, rfile, length, lang="zh"):
        base = re.sub(r"[^A-Za-z0-9._-]+", "_", os.path.basename(name)).strip("._") or "video.mp4"
        stem, ext = os.path.splitext(base)
        media_ext = ext.lower()
        if media_ext not in MEDIA_TYPES:
            return None, f"unsupported file type {ext or '(none)'}; use {', '.join(MEDIA_TYPES)}"
        os.makedirs(UPLOADS, exist_ok=True)
        left = length
        with tempfile.NamedTemporaryFile(dir=UPLOADS, suffix=".part") as pending:
            while left > 0:
                chunk = rfile.read(min(1 << 20, left))
                if not chunk:
                    return None, "upload interrupted"
                pending.write(chunk)
                left -= len(chunk)
            pending.flush()
            try:
                media = probe_media(pending.name, media_ext)
            except subprocess.CalledProcessError:
                media = None
            except (OSError, ValueError, subprocess.SubprocessError):
                return None, "Could not check the audio track; retry the upload"
            if media is None or not can_decode_audio(pending.name, media_ext, media.audio_index):
                return None, "No usable audio track for this file type"
            name, suffix = base, 1
            with self.lock:
                while True:
                    dst = os.path.join(UPLOADS, name)
                    name, suffix = f"{stem}-{suffix}{ext}", suffix + 1
                    if os.path.lexists(dst):
                        continue
                    # Keep a new upload from claiming an existing video's old full-name JSON.
                    dst_stem = os.path.splitext(dst)[0]
                    if Path(dst_stem).suffix.lower() in MEDIA_TYPES and os.path.isfile(dst_stem) and os.path.isfile(dst_stem + ".json"):
                        continue
                    sidecar = meta_of(dst)
                    try:
                        metadata = open(sidecar, "x")
                    except FileExistsError:
                        continue
                    published = False
                    try:
                        with metadata:
                            json.dump({"lang": lang if lang in LANGS else "zh"}, metadata)
                        # Publish complete media atomically, after its language is readable.
                        os.link(pending.name, dst)
                        published = True
                    except FileExistsError:
                        continue
                    finally:
                        if not published:
                            os.unlink(sidecar)
                    st = os.stat(dst)
                    self.media_info[dst] = (st.st_ino, st.st_size, st.st_mtime_ns), media
                    return {"id": os.path.relpath(dst, MEDIA), "duration_s": media.duration_s, "kind": media.kind}, None

    def delete(self, vid):
        with self.lock:
            p = media_path(vid)
            if p is None or Path(p).suffix.lower() not in MEDIA_TYPES or not p.startswith(os.path.normpath(UPLOADS) + os.sep):
                return "Only uploaded media files can be deleted"
            # Resolve ownership while all of the legacy records still exist.
            for sidecar in tuple(video_sidecars(p, deleting=True)):
                Path(sidecar).unlink(missing_ok=True)
            Path(p).unlink()
            self.media_info.pop(p, None)
        if self.video == vid:
            self.stop()
        return None

    # ------------------------------------------------------------ engine (worker thread only)
    def worker(self):
        recording = None
        while not self.stopping.is_set():
            with self.lock:
                state, sid = self.state, self.sid
                block = self.audio.popleft()[1] if state == "running" and self.audio else None
                finish = self.ended and block is None
                lang = self.lang
            try:
                if state not in ("reload", "error") and self.translations.reload_required.is_set():
                    raise RuntimeError("Translation model failed; reload models")
                if state == "reload":
                    recording = None
                    self.reload()
                elif state == "reset":
                    self.asr.call("start", lang)
                    recording = sid
                    segmenter = Segmenter(lang, 0)
                    frames = 0
                    started = time.monotonic()
                    with self.lock:
                        if self.sid == sid and self.state == "reset":
                            self.state = "running"
                            self.broadcast({"type": "reset", "sid": sid, "offset_s": self.offset_s, "jump": self.jump})
                            self.broadcast({"type": "state", "sid": sid, "state": "running"})
                elif state == "running" and block is not None:
                    before = time.monotonic()
                    update = self.asr.call("feed", block)
                    frames += len(block) // 2
                    with self.lock:
                        if self.sid == sid and self.state == "running":
                            self.buffered_audio -= len(block)
                    elapsed = time.monotonic() - before
                    self.accept_text(sid, update["delta"], segmenter, frames, started, elapsed,
                                     len(block) / 2 / SAMPLE_RATE, recoveries=update["recoveries"])
                    if update["finish_reason"]:
                        result = self.asr.call("finish")
                        recording = None
                        self.finish(sid, result, segmenter, frames, started)
                elif state == "running" and finish:
                    result = self.asr.call("finish" if frames else "discard")
                    recording = None
                    self.finish(sid, result, segmenter, frames, started)
                elif recording is not None and state != "running":
                    self.asr.call("discard")
                    recording = None
                else:
                    self.stopping.wait(0.02)
            except (OSError, RuntimeError, ValueError) as error:
                recording = None
                with self.lock:
                    if self.stopping.is_set():
                        return
                    self.state, self.ended, self.reload_required = "error", True, True
                    self.audio.clear()
                    self.buffered_audio = 0
                    self.model_error = str(error)
                    self.translations.cancel()
                    self.broadcast({"type": "state", "sid": self.sid, "state": "error",
                                        "reload_required": True, "error": self.model_error})

    def accept_text(self, sid, piece, segmenter, frames, started, elapsed=0.0, chunk_s=0.0, *, recoveries=()):
        audio_s = frames / SAMPLE_RATE
        with self.lock:
            if self.sid != sid or self.state != "running":
                return
            parts = []
            if piece:
                self.transcript += piece
                self.text_revision += 1
                parts.append({"id": 1, "piece": piece, "start_s": self.offset_s, "revision": self.text_revision})
            event = {
                "type": "text", "sid": sid, "piece": piece, "parts": parts,
                "audio_s": round(audio_s+self.offset_s, 2),
                "elapsed_ms": round(1000*elapsed, 1),
                "rtf": elapsed/chunk_s if chunk_s else None,
                "first_char_s": round(time.monotonic()-started, 2) if self.text_revision == 1 and piece else None,
            }
            if recoveries:
                event["asr_recoveries"] = recoveries
            self.broadcast(event)
        for segment in segmenter.push(piece, audio_s) if piece else segmenter.tick(audio_s):
            self.translations.submit(sid, segment)

    def finish(self, sid, result, segmenter, frames, started):
        reason = result["finish_reason"] if result else "stop"
        if result:
            self.accept_text(sid, result["delta"], segmenter, frames, started)
        for segment in segmenter.finish():
            self.translations.submit(sid, segment)
        with self.lock:
            if self.sid == sid and self.state == "running":
                self.state = "done"
                self.audio.clear()
                self.buffered_audio = 0
                self.broadcast({"type": "state", "sid": sid, "state": "done", "reason": reason,
                                    "audio_s": round(self.offset_s + frames/SAMPLE_RATE, 2)})

    def reload(self):
        self.close_workers(allow_failed_worker=self.needs_reload())
        self.load_workers()
        with self.lock:
            self.reload_required, self.model_error = False, None
            self.state = "idle"
            self.translations.begin(self.sid, self.lang, self.target)
        self.broadcast(self.info())
        self.broadcast({"type": "loading", "on": False})

    def close(self):
        if self._closed:
            return
        self.stopping.set()
        if self.translations is not None:
            self.translations.cancel()
        for thread in (self.worker_thread, self.sysmon_thread):
            if thread is not None:
                thread.join()
        self.close_workers()
        self._closed = True
        print('{"session_closed": true}', flush=True)


